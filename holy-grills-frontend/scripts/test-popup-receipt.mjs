import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'node_modules/.cache-popup-receipt.mjs');
execFileSync(join(root, 'node_modules/.bin/esbuild'), [join(root, 'src/lib/popupReceipt.ts'), '--format=esm', `--outfile=${out}`]);
const { popupDue, popupReceiptKey, popupRevision, POPUP_INTERVAL_MS } = await import(out);
const now = 100000000;
const revision = popupRevision({ id: 'one', updated_at: 'first', content: { image_url: 'image', placement: 'home' } });
assert.equal(popupDue(null, revision, now), true);
assert.equal(popupDue({ revision, shownAt: now }, revision, now + POPUP_INTERVAL_MS - 1), false);
assert.equal(popupDue({ revision, shownAt: now }, revision, now + POPUP_INTERVAL_MS), true);
assert.equal(popupDue({ revision, shownAt: now }, `${revision}-changed`, now + 1), true);
assert.equal(popupDue({ revision, shownAt: now + 1 }, revision, now), true);
assert.equal(popupDue({ revision, shownAt: 'bad' }, revision, now), true);
assert.notEqual(popupReceiptKey('campus-a', 'home', 'one'), popupReceiptKey('campus-b', 'home', 'one'));
assert.notEqual(popupReceiptKey('campus-a', 'home', 'one'), popupReceiptKey('campus-a', 'menu', 'one'));
assert.notEqual(revision, popupRevision({ id: 'one', updated_at: 'first', content: { image_url: 'new-art', placement: 'home' } }));
console.log('PASS popup receipt expiry, revision changes, clock recovery and campus/page isolation');
